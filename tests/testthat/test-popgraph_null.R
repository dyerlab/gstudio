  g <- suppressWarnings(population_graph(d, alpha = 0.01))
  seen <- NULL
  local_mocked_bindings(popgraph = function(x, groups, alpha = 0.05, tol = 1e-4) {
    seen <<- c(seen, alpha); igraph::make_ring(1)
  })
