test_that("the balanced kernel is symmetric and doubly stochastic", {
  x <- c(0, 1, 1.5, 5, 9, 30)
  B <- gstudio:::.pgn_balance(exp(-abs(outer(x, x, "-")) / 4))
  expect_equal(rowSums(B), rep(1, 6), tolerance = 1e-8)
  expect_equal(colSums(B), rep(1, 6), tolerance = 1e-8)
  expect_lt(max(abs(B - t(B))), 1e-8)
  expect_true(all(diag(B) == 0))
  M <- gstudio:::.pgn_mix(B, 0.1)
  expect_equal(unname(diag(M)), rep(0.9, 6))
  expect_equal(rowSums(M), rep(1, 6), tolerance = 1e-8)
})

test_that("Wright-Fisher drift keeps frequencies valid and is neutral in expectation", {
  set.seed(1)
  M <- diag(4); p0 <- list(L1 = c(0.3, 0.7), L2 = c(0.2, 0.5, 0.3))
  P <- gstudio:::.pgn_wf(p0, M, Ne = 50, ngen = 0)
  expect_equal(P$L1[1, ], c(0.3, 0.7))
  P <- replicate(400, gstudio:::.pgn_wf(p0, M, Ne = 50, ngen = 5)$L2[1, ])
  expect_equal(rowMeans(P), c(0.2, 0.5, 0.3), tolerance = 0.03)
  expect_true(all(abs(colSums(P) - 1) < 1e-12))
})

test_that("sampled genotypes are coded as to_mv() dosages", {
  set.seed(2)
  P <- list(L1 = matrix(c(1, 0, 0.5, 0.5), 2, byrow = TRUE))
  X <- gstudio:::.pgn_genotypes(P, c(A = 3, B = 4))
  expect_equal(dim(X$mv), c(7, 2))
  expect_true(all(rowSums(X$mv) == 1))
  expect_true(all(X$mv[1:3, 1] == 1))
  expect_equal(levels(X$groups), c("A", "B"))
})

test_that("popgraph_null() returns a calibration for a design", {
  data(arapat)
  d <- droplevels(arapat[arapat$Species == "Peninsula", ])
  d <- droplevels(d[d$Population %in% names(which(table(d$Population) >= 9)), ])
  lat <- tapply(d$Latitude, d$Population, mean)
  set.seed(3)
  nl <- suppressWarnings(popgraph_null(d, axis = -lat, nsim = 5, ngen = 50, pilot = 2))
  expect_s3_class(nl, "popgraph_null")
  expect_equal(nrow(nl$null), 5)
  expect_true(all(c("dR2", "slope_ratio", "r_S", "degree_share", "n_comp", "gst", "hs") %in% names(nl$null)))
  expect_gte(nl$cutoff[["all"]], 0)
  expect_true(nl$p.value[["dR2"]] > 0 && nl$p.value[["dR2"]] <= 1)
  expect_equal(nl$design$K, nlevels(factor(d$Population)))
  expect_output(print(nl), "Design-matched symmetric null")
  expect_error(popgraph_null(d, axis = c(a = 1)), "named by every stratum")
})

test_that("simulated genotypes carry the observed missing pattern", {
  set.seed(5)
  P <- list(L1 = matrix(0.5, 2, 2), L2 = matrix(c(0.2, 0.8), 2, 2, byrow = TRUE))
  miss <- list(L1 = c(TRUE, FALSE, FALSE, FALSE, TRUE), L2 = rep(FALSE, 5))
  X <- gstudio:::.pgn_genotypes(P, c(A = 2, B = 3), miss)
  expect_true(all(is.na(X$by_locus$L1[c(1, 5), ])))
  expect_true(all(X$mv[c(1, 5), 1:2] == 0))
  expect_false(anyNA(X$mv))
  fr <- gstudio:::.pgn_freqs(X$by_locus$L1, X$groups)
  expect_equal(unname(fr$n), c(1, 2))
  sf <- gstudio:::.pgn_sample_freqs(P, list(c(A = 0, B = 3), c(A = 2, B = 3)))
  expect_true(all(is.na(sf[[1]]$p[1, ])))
})

test_that("popgraph_null() builds null graphs at the observed graph's alpha", {
  data(arapat)
  d <- droplevels(arapat[arapat$Species == "Peninsula", ])
  d <- droplevels(d[d$Population %in% names(which(table(d$Population) >= 9)), ])
  lat <- tapply(d$Latitude, d$Population, mean)
  g <- suppressWarnings(population_graph(d, alpha = 0.01))
  seen <- NULL
  local_mocked_bindings(popgraph = function(x, groups, alpha = 0.05, tol = 1e-4) {
    seen <<- c(seen, alpha); igraph::make_ring(1)
  })
  set.seed(6)
  suppressWarnings(popgraph_null(d, axis = -lat, graph = g, nsim = 2, ngen = 10, pilot = 1))
  expect_equal(unique(seen), 0.01)
})
