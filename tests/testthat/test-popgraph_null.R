test_that("popgraph_null() accepts one Ne per stratum", {
  strata <- c("A", "B", "C", "D")
  expect_equal(gstudio:::.pgn_check_Ne(50, strata), c(A = 50, B = 50, C = 50, D = 50))
  expect_equal(gstudio:::.pgn_check_Ne(c(D = 4, B = 2, A = 1, C = 3), strata), c(A = 1, B = 2, C = 3, D = 4))
  expect_equal(gstudio:::.pgn_check_Ne(c(10.4, 20.6, 0.2, 5), strata), c(A = 10, B = 21, C = 1, D = 5))
  expect_error(gstudio:::.pgn_check_Ne(c(1, 2), strata), "length 1 or 4")
  expect_error(gstudio:::.pgn_check_Ne(c(A = 1, B = 2, C = 3, E = 4), strata), "named by every stratum")
  expect_error(gstudio:::.pgn_check_Ne(c(1, -2, 3, 4), strata), "positive")

  # drift is stronger in a small stratum
  set.seed(7)
  p0 <- list(L1 = c(0.5, 0.5))
  P <- replicate(200, gstudio:::.pgn_wf(p0, diag(2), Ne = c(5, 500), ngen = 20)$L1[, 1])
  expect_gt(var(P[1, ]), 10 * var(P[2, ]))

  data(arapat)
  d <- droplevels(arapat[arapat$Species == "Peninsula", ])
  d <- droplevels(d[d$Population %in% names(which(table(d$Population) >= 9)), ])
  lat <- tapply(d$Latitude, d$Population, mean)
  ne <- setNames(seq(40, 160, length.out = length(lat)), names(lat))
  set.seed(8)
  nl <- suppressWarnings(popgraph_null(d, axis = -lat, Ne = rev(ne), nsim = 4, ngen = 30, pilot = 2))
  expect_equal(nl$strata$Stratum, levels(factor(d$Population)))
  expect_equal(nl$strata$Ne, unname(round(ne[nl$strata$Stratum])))
  expect_equal(nl$tuning[["Ne"]], mean(round(ne)))
  expect_true(all(c("cor_S_S0", "var_degree", "max_mean_degree") %in% names(nl$null)))
  expect_named(nl$structure, c("degree_share", "cor_S_S0", "var_degree", "max_mean_degree"))
  expect_true(all(nl$structure >= 0 & nl$structure <= 1, na.rm = TRUE))
  expect_true(all(is.finite(nl$strata$hs_observed)))
  expect_output(print(nl), "Ne = 40-160")
  expect_output(print(nl), "Graph structure")
})

test_that("a vector of equal Ne reproduces the scalar Ne", {
  data(arapat)
  d <- droplevels(arapat[arapat$Species == "Peninsula", ])
  d <- droplevels(d[d$Population %in% names(which(table(d$Population) >= 9)), ])
  lat <- tapply(d$Latitude, d$Population, mean)
  set.seed(9); a <- suppressWarnings(popgraph_null(d, axis = -lat, Ne = 60, nsim = 3, ngen = 20, pilot = 1))
  set.seed(9); b <- suppressWarnings(popgraph_null(d, axis = -lat, Ne = rep(60, length(lat)), nsim = 3, ngen = 20, pilot = 1))
  expect_equal(a$null, b$null)
  expect_equal(a$tuning, b$tuning)
})
